# =========================================================
# GENERATE AUDIO
# =========================================================

async def _generate(
    text: str,
    output_path: Path,
):
    communicate = edge_tts.Communicate(
        text=text,

        voice=TAMIL_VOICE,

        # Slightly slower sounds better
        # for farmer-facing instructions.
        rate="-7%",

        # Slightly softer/deeper delivery.
        pitch="-2Hz",

        volume="+0%",
    )

    await communicate.save(
        str(output_path)
    )


# =========================================================
# GET / CREATE QUESTION AUDIO
# =========================================================

def generate_question_audio(
    field: str,
) -> Path:

    text = TAMIL_QUESTIONS.get(
        field
    )

    if not text:
        raise ValueError(
            f"Unknown Tamil field: {field}"
        )

    output_path = (
        OUTPUT_DIR
        / f"{field}.mp3"
    )

    # -----------------------------------------------------
    # USE ALREADY GENERATED AUDIO
    # -----------------------------------------------------

    if (
        output_path.exists()
        and output_path.stat().st_size > 0
    ):
        return output_path

    print(
        "Generating farmer-style Tamil audio:",
        field,
    )

    asyncio.run(
        _generate(
            text,
            output_path,
        )
    )

    print(
        "Tamil audio generated:",
        output_path,
    )

    return output_path